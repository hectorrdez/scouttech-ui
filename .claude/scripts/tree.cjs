#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { CLAUDE_DIR, REPO_ROOT } = require('./_lib.cjs');

const outPath = path.join(CLAUDE_DIR, 'tree.md');

// git ls-files respects .gitignore for free: no node_modules, dist, .env noise.
// --cached = tracked, --others --exclude-standard = new files not yet committed (but not ignored).
const res = spawnSync('git', ['ls-files', '--cached', '--others', '--exclude-standard'], {
  cwd: REPO_ROOT,
  encoding: 'utf8',
  shell: true,
});
if (res.status !== 0) {
  console.log('ERROR: git ls-files failed');
  process.exit(1);
}

const files = res.stdout.split(/\r?\n/).filter(Boolean);
const lines = ['# Project file tree (generated by tree.cjs - do not edit by hand)', '', ...files.map((f) => `- ${f}`)];
fs.writeFileSync(outPath, lines.join('\n') + '\n');
console.log(`OK: tree written to ${outPath}`);
process.exit(0);
